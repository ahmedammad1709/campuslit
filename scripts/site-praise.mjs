// Builds the "What people are saying" section of the home page from scripts/data/testimonials.json and writes it into site/index.html
// between the praise markers (first run: just before the install section). Run again after editing the data:  node scripts/site-praise.mjs
// A comment is only listed with the permission of the person who wrote it. Optional field "photo": a file in site/assets/people/ (otherwise initials).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'scripts', 'data', 'testimonials.json'), 'utf8'));
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const initials = n => { const w = n.replace(/^(Engr|Dr|Mr|Ms|Mrs)\.?\s+/i, '').split(/\s+/).filter(Boolean); return ((w[0] || '?')[0] + (w.length > 1 ? w[w.length - 1][0] : '')).toUpperCase(); };
const IN = '<span class="tin" aria-hidden="true">in</span>';
const LIKE = '<svg viewBox="0 0 24 24" width="15" height="15" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M7 11v9H4v-9h3Zm0 0 4-7c1.5 0 2.5 1 2.5 2.5V9H19a2 2 0 0 1 2 2.3l-1 6A2.5 2.5 0 0 1 17.5 19H7"/></svg>';

const avatar = (c, i, cls = '') => {
  if (c.photo) return `<img class="tav ${cls}" src="assets/people/${esc(c.photo)}" alt="" width="46" height="46" loading="lazy" decoding="async">`;
  return `<span class="tav c${i % 6} ${cls}" aria-hidden="true">${esc(initials(c.name))}</span>`;
};
const card = (c, i) => `<a class="tcard" href="${esc(data.post.url)}" rel="noopener" aria-label="Comment by ${esc(c.name)} on LinkedIn: open the post">
              ${avatar(c, i)}
              <span class="tbody">
                <span class="tname">${esc(c.name)} ${IN}</span>
                <span class="trole">${esc(c.role)}</span>
                <span class="tq">&ldquo;${esc(c.quote)}&rdquo;</span>
                <span class="tfoot"><span>LinkedIn</span><span class="tgo">View post &rarr;</span></span>
              </span>
            </a>`;
const rows = [[], [], []];
data.comments.forEach((c, i) => rows[i % 3].push(card(c, i)));
const row = (cards, rev) => `<div class="row${rev ? ' rev' : ''}"><div class="track">
            ${cards.join('\n            ')}
          </div></div>`;
const p = data.post;
const section = `<!-- praise:start (generated by scripts/site-praise.mjs from scripts/data/testimonials.json) -->
  <section id="praise" aria-labelledby="praise-title">
    <div class="wrap">
      <div class="section-head center reveal">
        <p class="kicker">Loved by students and developers</p>
        <h2 id="praise-title">What people are saying</h2>
        <p>Real comments from my LinkedIn post, shared with permission. Every card opens the original post.</p>
      </div>
      <div class="praise reveal">
        <article class="lpost" aria-label="The LinkedIn post">
          <div class="lp-face">
            <div class="lp-head">
              <span class="tav big c0" aria-hidden="true">${esc(initials(p.author))}</span>
              <div><b>${esc(p.author)}</b><small>${esc(p.headline)}</small></div>
              <span class="tin big" aria-hidden="true">in</span>
            </div>
            <p class="lp-text">${p.text.map(esc).join('<br>')}</p>
            <div class="lp-media"><img src="assets/shots/lms-bahria.webp" width="2040" height="1275" loading="lazy" decoding="async" alt="The Bahria University LMS dashboard redesigned by Campuslit, as shown in the post."><span class="play" aria-hidden="true"></span></div>
            <p class="lp-stats"><span>${LIKE} ${p.reactions} reactions</span><span>${p.comments} comments</span><span>as of ${esc(p.asOf)}</span></p>
            <div class="lp-actions">
              <button class="btn btn-primary btn-sm" type="button" data-embed="${esc(p.embed)}">Show the full post here</button>
              <a class="btn btn-ghost btn-sm" href="${esc(p.url)}" rel="noopener">View on LinkedIn</a>
            </div>
            <p class="lp-note">The full post loads from LinkedIn when you scroll here.</p>
          </div>
          <div class="lp-host" hidden></div>
        </article>
        <div class="wall" aria-label="Comments from LinkedIn">
          ${row(rows[0], false)}
          ${row(rows[1], true)}
          ${row(rows[2], false)}
        </div>
      </div>
      <div class="cta-row reveal"><a class="btn btn-primary" href="${esc(p.url)}" rel="noopener">See more on LinkedIn</a></div>
    </div>
  </section>
  <!-- praise:end -->
`;

const file = path.join(root, 'site', 'index.html');
let html = fs.readFileSync(file, 'utf8');
const crlf = html.includes('\r\n'); html = html.split('\r\n').join('\n');
const a = html.indexOf('<!-- praise:start'), b = html.indexOf('<!-- praise:end -->');
if (a >= 0 && b > a) html = html.slice(0, a) + section.trimEnd() + html.slice(b + '<!-- praise:end -->'.length);
else {
  const mark = '  <!-- ============ install ============ -->';
  if (!html.includes(mark)) throw new Error('install marker not found');
  html = html.replace(mark, () => section + '\n' + mark);
}
fs.writeFileSync(file, crlf ? html.split('\n').join('\r\n') : html);
console.log('praise section written:', data.comments.length, 'comments');
